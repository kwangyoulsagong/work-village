#!/bin/sh
# Bundles the game from aquila/ into the Claude Code mod (claude-mod/hooks/game.gen.js): every game file inside one
# function that takes the browser stand-ins (claude-mod/hooks/host.js) and returns handles the mod drives it by.
# Run after changing the game, like ./build-chrome.sh. The game itself stays in aquila/.
set -e
cd "$(dirname "$0")"
OUT=claude-mod/hooks/game.gen.js
HIDDEN=$(grep -oE 'id="[^"]+"[^>]*[[:space:]]hidden[[:space:]>]' aquila/index.html | sed -E 's/id="([^"]+)".*/"\1"/' | paste -sd, -)
FILES="art.js ai.js extras.js chaos.js jobs.js layout.js life.js fun.js more.js visit.js game.js"
{
  echo "// GENERATED by build-claude-mod.sh from aquila/*.js. Edit the game there, then run the script again."
  echo "// @ts-nocheck"
  echo "/* eslint-disable */"
  echo "// The page's elements that start hidden (aquila/index.html), so the stand-ins start the same way."
  echo "export const HIDDEN_IDS = [$HIDDEN];"
  echo "export function makeGame(env) {"
  echo "  const { document, window, aquila, navigator, requestAnimationFrame, cancelAnimationFrame, setTimeout, clearTimeout,"
  echo "    setInterval, clearInterval, ResizeObserver, IntersectionObserver, CompressionStream, DecompressionStream, Blob,"
  echo "    Response, TextEncoder, TextDecoder, btoa, atob } = env;"
  for f in $FILES; do
    echo "  // ── aquila/$f"
    # 'use strict' is the module's anyway; the game starts itself at the end of game.js (start()).
    sed -e "/^'use strict';$/d" "aquila/$f"
  done
  cat <<'API'
  // ── What the mod reads and drives
  return {
    get S() { return S; },
    get MODE() { return MODE; },
    get VISIT() { return VISIT; },
    get camX() { return camX; },
    get chaosCam() { return chaosCam; },
    set chaosCam(v) { chaosCam = v; },
    get chaosTool() { return chaosTool; },
    set chaosTool(v) { chaosTool = v; },
    get nick() { return nick; },
    set nick(v) { nick = v; },
    get weather() { return weather; },
    get holiday() { return holiday; },
    get people() { return people; },
    get me() { return me; },
    T, W, H, VIEW_W, ERAS, CHAOS_TOOLS, TRAITS, LANDMARKS,
    levelOf, fmt, nextGoal, storyItems, storyKind, population, isNight, seasonNow, SEASONS,
    paintUi, wake, moveCam, pickGender, spawnFamily, ensureLots, useTool, enterChaos, leaveChaos, placeSign,
    myCode, openCode, leaveVisit, visitNote, openVisitCard,
    $: (id) => document.getElementById(id),
  };
}
API
} > "$OUT"
echo "claude-mod/ updated ($(wc -c < "$OUT" | tr -d ' ') bytes)"
